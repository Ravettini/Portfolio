import { chromium } from '../tools/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const baseURL = process.env.PORTFOLIO_TEST_URL || 'http://localhost:3000';
const checks = [], errors = [];
const assert = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
page.on('pageerror', error => errors.push(error.message));
await page.goto(baseURL, { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Entrar como visitante' }).click();
await page.locator('.os-session[data-phase="desktop"]').waitFor();
assert(await page.locator('[data-app-window]').count() === 1, 'Only the welcome note is initially open');
const note = await page.locator('[data-app-window="welcome"]').boundingBox();
assert(Math.abs(note.x + note.width / 2 - 720) < 2, 'Welcome note is horizontally centered');
assert(Math.abs(note.y + note.height / 2 - 480) < 80, 'Welcome note is centered in the workspace above the dock');
await page.screenshot({ path: '.impeccable/review/refinements-desktop.png', fullPage: true });

const sigmaIcon = page.locator('.desktop-app[data-launcher="sigma"]');
const original = await sigmaIcon.boundingBox();
await page.mouse.move(original.x + 45, original.y + 25); await page.mouse.down();
await page.mouse.move(original.x + 45 + 230, original.y + 25 + 30, { steps: 12 }); await page.mouse.up();
const moved = await sigmaIcon.boundingBox();
assert(moved.x !== original.x && Math.abs((moved.x-original.x)/109-Math.round((moved.x-original.x)/109)) < .01, 'Desktop icon drag snaps to a grid slot');
assert(await page.locator('[data-app-window="sigma"]').count() === 0, 'Dragging an icon does not open its application');
await page.waitForTimeout(400);
await page.reload({ waitUntil: 'networkidle' });
await page.locator('.os-session[data-phase="desktop"]').waitFor();
const persisted = await sigmaIcon.boundingBox();
assert(Math.abs(persisted.x - moved.x) < 2 && Math.abs(persisted.y - moved.y) < 2, 'Moved icon position survives reload');
await sigmaIcon.focus(); await page.keyboard.press('Alt+ArrowRight');
const keyboardMoved = await sigmaIcon.boundingBox();
assert(Math.abs(keyboardMoved.x - persisted.x - 109) < 2, 'Alt and arrow keys move desktop icons between grid slots');

await page.mouse.move(700, 100);
await page.getByRole('button', { name: 'Abrir Contacto', exact: true }).hover();
const tooltip = page.locator('.dock-app[data-launcher="contact"] .dock-tooltip');
await page.waitForTimeout(2600);
assert(await tooltip.evaluate(el => getComputedStyle(el).opacity) === '0', 'Dock tooltip stays hidden before three seconds, including reduced motion');
await page.waitForTimeout(550);
assert(await tooltip.evaluate(el => Number(getComputedStyle(el).opacity)) > .9, 'Dock tooltip appears after three seconds');
await page.mouse.move(700, 100);
assert(await tooltip.evaluate(el => getComputedStyle(el).opacity) === '0', 'Dock tooltip clears when pointer leaves');

await page.locator('.desktop-app[data-launcher="acreditapp"]').click();
const project = page.locator('[data-app-window="acreditapp"]');
await project.locator('.window-control--maximize').click();
assert(await page.locator('.os-desktop--immersive').count() === 1, 'Maximized window activates an immersive workspace');
const maximized = await project.boundingBox();
assert(maximized.y + maximized.height > 940, 'Maximized window uses the space previously reserved for the dock');
assert(await page.locator('.os-dock').evaluate(el => getComputedStyle(el).opacity) === '0', 'Dock is hidden by default when window is maximized');
const contentWidth = await project.locator('.project-app').evaluate(el => el.getBoundingClientRect().width);
assert(contentWidth <= 1160, 'Maximized project content stays at a readable width');
await page.screenshot({ path: '.impeccable/review/maximized-hidden-dock.png' });
await page.mouse.move(720, 957);
await page.waitForTimeout(250);
assert(await page.locator('.os-dock').evaluate(el => Number(getComputedStyle(el).opacity)) > .9, 'Moving pointer to the lower edge reveals dock');
await page.mouse.move(720, 885);
await page.screenshot({ path: '.impeccable/review/maximized-revealed-dock.png' });
await page.mouse.move(300, 100); await page.waitForTimeout(600);
assert(await page.locator('.os-dock').evaluate(el => getComputedStyle(el).opacity) === '0', 'Dock hides again after leaving');
await page.getByRole('button', { name: 'Abrir Perfil', exact: true }).focus();
assert(await page.locator('.os-dock').evaluate(el => Number(getComputedStyle(el).opacity)) > .9, 'Keyboard focus reveals hidden dock');
await project.locator('.window-control--maximize').click();
assert(await page.locator('.os-desktop--immersive').count() === 0, 'Restoring window restores ordinary dock layout');
await project.locator('.window-control--close').click();
await page.getByRole('button', { name: 'Abrir Ajustes', exact: true }).click();
await page.getByRole('button', { name: 'Ordenar escritorio', exact: true }).click();
const resetIcon = await sigmaIcon.boundingBox();
assert(Math.abs(resetIcon.x - original.x) < 2, 'Order desktop restores the icon grid');
assert(await page.locator('[data-app-window]').count() === 1, 'Order desktop restores only the welcome note');
for (const viewport of [{ width: 1920, height: 880 }, { width: 1536, height: 704 }]) {
  await page.setViewportSize(viewport);
  await page.screenshot({ path: `.impeccable/review/refinements-user-${viewport.width}.png` });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No overflow at user screenshot viewport ${viewport.width}`);
}

const servedCV = await page.request.get(`${baseURL}/cv-ignacio-ravettini.pdf`);
const cvBytes = await servedCV.body();
const newCV = await fs.readFile('C:/Users/20462657693/Downloads/Cv Ignacio Ravettini-3(1).pdf');
assert(createHash('sha256').update(cvBytes).digest('hex') === createHash('sha256').update(newCV).digest('hex'), 'Served CV exactly matches the new PDF supplied by the user');
assert(cvBytes.subarray(0, 5).toString() === '%PDF-', 'Updated CV is a valid PDF response');

const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
mobile.on('pageerror', error => errors.push(error.message));
await mobile.goto(baseURL, { waitUntil: 'networkidle' });
await mobile.getByRole('button', { name: 'Entrar como visitante' }).tap();
await mobile.locator('.os-session[data-phase="desktop"]').waitFor();
await mobile.locator('.desktop-app[data-launcher="sigma"]').tap();
const mobileApp = mobile.locator('[data-app-window="sigma"]');
assert(await mobileApp.isVisible(), 'Mobile icon still opens on tap without accidental dragging');
await mobileApp.locator('.window-control--maximize').tap();
assert(await mobile.locator('.os-dock').evaluate(el => getComputedStyle(el).opacity) === '0', 'Mobile maximized app also hides dock');
await mobile.screenshot({ path: '.impeccable/review/refinements-mobile-maximized.png' });
await mobile.getByRole('button', { name: 'Mostrar aplicaciones', exact: true }).tap();
assert(await mobile.locator('.os-dock').evaluate(el => Number(getComputedStyle(el).opacity)) > .9, 'Mobile lower-edge affordance reveals dock by touch');
await mobile.waitForTimeout(2700);
const touch = await mobile.context().newCDPSession(mobile);
await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 195, y: 838 }] });
await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 195, y: 790 }] });
await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
assert(await mobile.locator('.os-dock').evaluate(el => Number(getComputedStyle(el).opacity)) > .9, 'Swiping upward from the mobile lower edge reveals dock');
assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow on mobile');
assert(errors.length === 0, 'No client runtime exceptions');
await fs.writeFile('.impeccable/review/refinements-verification.json', JSON.stringify({ checks, errors }, null, 2));
console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
await browser.close();
