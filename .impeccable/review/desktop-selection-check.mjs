import { chromium } from '../tools/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'});
const checks=[],errors=[];
const assert=(value,message)=>{if(!value)throw new Error(message);checks.push(message);};
const baseURL=process.env.PORTFOLIO_TEST_URL||'http://localhost:3000';
page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(()=>sessionStorage.setItem('ravettini-os-session','visitor'));
await page.goto(baseURL,{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Cerrar Bienvenida',exact:true}).click();
const button=id=>page.locator(`.desktop-app[data-launcher="${id}"]`);
const rect=id=>button(id).boundingBox();
const positions=()=>page.locator('.desktop-app').evaluateAll(els=>Object.fromEntries(els.map(el=>{const r=el.getBoundingClientRect();return[el.dataset.launcher,{x:r.x,y:r.y}];})));
const sigma=await rect('sigma');
await page.mouse.move(sigma.x+45,sigma.y+25);await page.mouse.down();
await page.mouse.move(sigma.x+45+227,sigma.y+25+43,{steps:10});
const preview=await rect('sigma');
assert(Math.abs(preview.x-sigma.x-227)<2&&Math.abs(preview.y-sigma.y-43)<2,'Held icon follows pointer freely before snapping');
await page.waitForTimeout(400);
const storedWhileHeld=await page.evaluate(()=>JSON.parse(localStorage.getItem('ravettini-os-icon-positions')));
assert(storedWhileHeld.sigma.x===sigma.x&&storedWhileHeld.sigma.y===sigma.y,'Unsnapped preview is not persisted');
await page.screenshot({path:'.impeccable/review/free-drag-held.png'});
await page.mouse.up();
const dropped=await rect('sigma');
assert((dropped.x-23)%109===0&&(dropped.y-112)%105===0,'Icon snaps to grid only on release');
assert(await page.locator('[data-app-window="sigma"]').count()===0,'Drag release does not launch app');

await page.getByRole('button',{name:'Menú de ravettiniOS',exact:true}).click();
await page.getByRole('button',{name:'Volver al inicio',exact:true}).click();
await page.getByRole('button',{name:'Cerrar Bienvenida',exact:true}).click();
await page.mouse.move(12,100);await page.mouse.down();await page.mouse.move(120,310,{steps:10});
assert(await page.locator('.desktop-selection-box').isVisible(),'Dragging desktop background draws a blue selection rectangle');
await page.screenshot({path:'.impeccable/review/desktop-selection-box.png'});
await page.mouse.up();
assert(await page.locator('.desktop-selection-box').count()===0,'Selection rectangle disappears on release');
assert(await page.locator('.desktop-app--selected').count()===2,'Rectangle selects multiple intersecting icons');
assert(await button('acreditapp').getAttribute('aria-pressed')==='true'&&await button('recursos-humanos-ssccrs').getAttribute('aria-pressed')==='true','Selected icons expose their selection state');
const beforeGroup=await positions();
const a=beforeGroup.acreditapp;
await page.mouse.move(a.x+45,a.y+25);await page.mouse.down();await page.mouse.move(a.x+45+333,a.y+25+29,{steps:10});
const heldGroup=await positions();
assert(Math.abs(heldGroup.acreditapp.x-beforeGroup.acreditapp.x-333)<2&&Math.abs(heldGroup['recursos-humanos-ssccrs'].x-beforeGroup['recursos-humanos-ssccrs'].x-333)<2,'Selected icons follow the pointer together');
await page.mouse.up();
const afterGroup=await positions();
assert(afterGroup.acreditapp.x!==beforeGroup.acreditapp.x&&afterGroup['recursos-humanos-ssccrs'].x!==beforeGroup['recursos-humanos-ssccrs'].x,'Group drop moves all selected icons to new cells');
assert(afterGroup['recursos-humanos-ssccrs'].y-afterGroup.acreditapp.y===105,'Group drop retains relative arrangement when space permits');
assert(new Set(Object.values(afterGroup).map(p=>`${p.x},${p.y}`)).size===11,'Group drop does not overlap any icon');
assert(Object.values(afterGroup).every(p=>(p.x-23)%109===0&&(p.y-112)%105===0),'All committed icons remain on the grid');

await button('sigma').click({modifiers:['Control']});
assert(await page.locator('.desktop-app--selected').count()===3,'Ctrl-click adds an icon to the selection');
assert(await page.locator('[data-app-window="sigma"]').count()===0,'Ctrl-click does not open the app');
await button('sigma').click({modifiers:['Control']});
assert(await page.locator('.desktop-app--selected').count()===2,'Ctrl-click removes a selected icon');
await button('sigma').focus();await page.keyboard.press('Control+Space');
assert(await page.locator('.desktop-app--selected').count()===3,'Ctrl-Space supports keyboard multiselection');
await page.keyboard.press('Escape');
assert(await page.locator('.desktop-app--selected').count()===0,'Escape clears the selection');

const beforeCancel=await rect('sigma');
await page.mouse.move(beforeCancel.x+45,beforeCancel.y+25);await page.mouse.down();await page.mouse.move(beforeCancel.x+245,beforeCancel.y+70,{steps:5});
await page.keyboard.press('Escape');await page.mouse.up();
const cancelled=await rect('sigma');
assert(cancelled.x===beforeCancel.x&&cancelled.y===beforeCancel.y,'Escape cancels an in-progress drag without saving its preview');
await page.mouse.move(700,700);await page.mouse.down();await page.mouse.move(900,850,{steps:5});await page.mouse.up();
assert(await page.locator('.desktop-app--selected').count()===0,'Empty rectangle clears selection');
await button('sigma').click();
assert(await page.locator('[data-app-window="sigma"]').isVisible(),'Normal single click still opens an app');
assert(errors.length===0,'No runtime exceptions');
await fs.writeFile('.impeccable/review/desktop-selection-verification.json',JSON.stringify({checks,errors},null,2));
console.log(JSON.stringify({passed:checks.length,checks,errors},null,2));
await browser.close();
