import { chromium } from '../tools/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const baseURL = process.env.PORTFOLIO_TEST_URL || 'http://localhost:3000';
const checks = [], errors = [];
const assert = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
page.on('pageerror', error => errors.push(error.message));
await page.goto(baseURL, { waitUntil: 'domcontentloaded' });
await page.locator('.os-boot').waitFor();
assert(await page.locator('.os-session-desktop').getAttribute('inert') !== null, 'Desktop is inert during startup');
await page.locator('.boot-center').evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)));
await page.screenshot({ path: '.impeccable/review/boot.png' });
await page.getByRole('button', { name: 'Entrar como visitante' }).waitFor();
assert(await page.locator('.os-login').isVisible(), 'Boot transitions to user selection');
await page.screenshot({ path: '.impeccable/review/login-desktop.png', animations: 'disabled' });
assert(await page.locator('input[type="password"]').count() === 0, 'Visitor entry needs no password');
await page.getByRole('button', { name: 'Entrar como visitante' }).click();
await page.locator('.os-session[data-phase="entering"]').waitFor();
await page.locator('.os-session[data-phase="desktop"]').waitFor();
await page.locator('.os-desktop').evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)));
await page.screenshot({ path: '.impeccable/review/desktop-session.png' });
const welcome = page.locator('[data-app-window="welcome"]');
await page.locator('.desktop-app[data-launcher="sigma"]').click();
await welcome.locator('.window-control--close').click();
assert(await welcome.count() === 0, 'Inactive welcome closes on the first pointer click (original reported bug)');
await page.getByRole('button', { name: 'Menú de ravettiniOS', exact: true }).click();
await page.getByRole('button', { name: 'Volver al inicio', exact: true }).click();
await page.locator('.desktop-app[data-launcher="acreditapp"]').click();
const project = page.locator('[data-app-window="acreditapp"]');
const projectBar = await project.locator('.os-window-bar').boundingBox();
await page.mouse.move(projectBar.x + projectBar.width / 2, projectBar.y + 20);
await page.mouse.down(); await page.mouse.move(projectBar.x + projectBar.width / 2 + 300, projectBar.y + 20, { steps: 10 }); await page.mouse.up();
await page.locator('.welcome-content h1').click();
await project.locator('.window-control--close').click();
assert(await project.count() === 0, 'Inactive project closes on the first click with another app in front');
await page.getByRole('button', { name: 'Abrir Perfil', exact: true }).click();
await page.locator('[data-app-window="profile"] .window-control--close').focus();
await page.keyboard.press('Enter');
assert(await page.locator('[data-app-window="profile"]').count() === 0, 'Keyboard Enter closes a window');
await page.getByRole('button', { name: 'Abrir Terminal', exact: true }).click();
await page.getByLabel('Comando de terminal').fill('keep my session');
await page.getByRole('button', { name: 'Menú de ravettiniOS', exact: true }).click();
await page.getByRole('button', { name: 'Cambiar usuario', exact: true }).click();
await page.getByRole('button', { name: 'Entrar como visitante' }).click();
await page.locator('.os-session[data-phase="desktop"]').waitFor();
assert(await page.getByLabel('Comando de terminal').inputValue() === 'keep my session', 'Switching user and returning preserves open apps');
await page.reload({ waitUntil: 'networkidle' });
assert(await page.locator('.os-session[data-phase="desktop"]').isVisible(), 'Reload resumes the tab session');
await page.getByRole('button', { name: 'Menú de ravettiniOS', exact: true }).click();
await page.getByRole('button', { name: 'Reiniciar sistema', exact: true }).click();
assert(await page.locator('.os-boot').isVisible(), 'Restart replays boot animation');
await page.getByRole('button', { name: 'Omitir animación', exact: true }).click();
assert(await page.getByRole('button', { name: 'Entrar como visitante' }).isVisible(), 'Boot animation can be skipped');
await page.getByRole('button', { name: 'Entrar como visitante' }).click();
await page.locator('.os-session[data-phase="desktop"]').waitFor();
assert(await page.locator('[data-app-window="terminal"]').count() === 0, 'Restart resets the desktop session');
await page.goto(`${baseURL}/proyectos/sigma`, { waitUntil: 'networkidle' });
await page.getByRole('link', { name: 'Escritorio', exact: true }).click();
await page.locator('.os-session[data-phase="desktop"]').waitFor();
assert(await page.locator('[data-app-window="projects"]').isVisible(), 'Case-study return resumes session and respects project anchor');
await page.getByRole('button', { name: 'Abrir Ajustes', exact: true }).click();
await page.getByRole('checkbox', { name: /Reducir movimiento/ }).check();
assert(await page.locator('.os-session--reduced').count() === 1, 'In-app reduced-motion preference updates startup immediately');
await page.getByRole('button', { name: /ravettiniOS/, exact: false }).first().click();
await page.getByRole('button', { name: 'Reiniciar sistema', exact: true }).click();
await page.getByRole('button', { name: 'Entrar como visitante' }).waitFor({ timeout: 1200 });
assert(await page.locator('.os-session--reduced').count() === 1, 'Restart honors reduced motion without reloading');

const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
mobile.on('pageerror', error => errors.push(error.message));
await mobile.goto(baseURL, { waitUntil: 'networkidle' });
await mobile.getByRole('button', { name: 'Entrar como visitante' }).waitFor();
await mobile.screenshot({ path: '.impeccable/review/login-mobile.png' });
assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'User selection fits mobile width');
assert(await mobile.locator('.os-session').evaluate(el => el.classList.contains('os-session--reduced')), 'Reduced motion is respected at startup');
await mobile.getByRole('button', { name: 'Entrar como visitante' }).tap();
await mobile.locator('.os-session[data-phase="desktop"]').waitFor();
await mobile.locator('.desktop-app[data-launcher="sigma"]').tap();
await mobile.locator('[data-app-window="sigma"] .window-control--close').tap();
assert(await mobile.locator('[data-app-window="sigma"]').count() === 0, 'Touch closes project on first tap');
assert(errors.length === 0, 'No client runtime exceptions in boot, login or window controls');
await fs.writeFile('.impeccable/review/session-verification.json', JSON.stringify({ checks, errors }, null, 2));
console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
await browser.close();
